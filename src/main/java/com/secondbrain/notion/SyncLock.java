package com.secondbrain.notion;

/**
 * Замок, разрешающий досылать очередь в Notion только кому-то одному.
 *
 * <p>Защищает от единственного, но дорогого исхода: два исполнителя берут из очереди
 * одну и ту же заметку и создают в Notion две страницы одной мысли.
 *
 * <p>Реализации различаются охватом:
 * <ul>
 *   <li>{@link JvmSyncLock} — внутри одного процесса; достаточно, когда работает
 *       только консоль;</li>
 *   <li>{@link SqliteSyncLock} — между процессами; нужен, когда рядом с консолью
 *       работает сервер с досылкой по расписанию.</li>
 * </ul>
 *
 * <p>Не захватить замок — штатная ситуация, а не ошибка: значит кто-то другой уже
 * этим занят, и заметка просто подождёт следующего раза.
 */
public interface SyncLock {

    /**
     * Пытается захватить замок, не дожидаясь освобождения.
     *
     * @return {@code true}, если захвачен — тогда вызывающий обязан вызвать
     *         {@link #release()} в {@code finally}
     */
    boolean tryAcquire();

    /** Освобождает замок. Безопасно вызывать, даже если он уже не наш. */
    void release();
}
