package com.secondbrain.model;

/**
 * Категория захваченной мысли.
 *
 * <p>Соответствует базам-назначениям в Notion (этап 2):
 * идея, задача, ссылка или свободная заметка.
 */
public enum NoteType {
    /** Идея, замысел, «а что если…». */
    IDEA,
    /** Задача, действие, дело — что-то, что нужно сделать. */
    TASK,
    /** Ссылка / ресурс, чтобы вернуться позже. */
    LINK,
    /** Свободная заметка — всё, что не попало в остальные категории. */
    NOTE
}
