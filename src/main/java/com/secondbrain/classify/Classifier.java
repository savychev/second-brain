package com.secondbrain.classify;

/**
 * Определяет категорию мысли по её тексту.
 *
 * <p>Этап 1 — реализация по правилам ({@link RuleBasedClassifier}).
 * Этап 4 — реализация через Anthropic API; она встанет на место этого интерфейса
 * без изменений в остальном коде.
 */
public interface Classifier {

    /**
     * Классифицирует текст мысли.
     *
     * @param text исходный текст (может быть любой длины)
     * @return категория с уверенностью и причиной; никогда не {@code null}
     */
    ClassificationResult classify(String text);

    /**
     * Готовит классификатор к первому настоящему запросу.
     *
     * <p>Нужно локальной модели: она загружается в память с диска, и первый
     * запрос из-за этого в разы дольше остальных — настолько, что не
     * укладывается в лимит ожидания и мысль уходит к правилам. Прогрев
     * при старте переносит эту задержку туда, где её никто не ждёт.
     *
     * <p>По умолчанию не делает ничего: реализациям по правилам и по сети
     * готовиться не к чему. Не должен бросать исключения — неудавшийся
     * прогрев не повод не запускать приложение.
     */
    default void warmUp() {
    }
}
